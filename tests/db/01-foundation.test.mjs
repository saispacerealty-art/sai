import { addUser, as, asService, createDb, denied, eq, ok, summary } from './harness.mjs'

const db = await createDb({ quiet: true })
const one = async (sql, p) => Object.values((await db.query(sql, p)).rows[0] ?? {})[0]

console.log('\n# Encryption')
{
  const c = await one(`select private.enc('9876543210')`)
  ok(c instanceof Uint8Array && c.length > 20, 'enc() returns ciphertext bytes')
  ok(!Buffer.from(c).toString('latin1').includes('9876543210'), 'ciphertext does not contain the plaintext')
  eq(c[0], 1, 'first byte is the key version')
  eq(await one(`select private.dec(private.enc('9876543210'))`), '9876543210', 'dec(enc(x)) = x')
  eq(await one(`select private.dec(private.enc('नमस्ते ₹85L'))`), 'नमस्ते ₹85L', 'round-trips unicode')
  ok((await one(`select private.enc('a') <> private.enc('a')`)) === true, 'same input encrypts differently each time')
  eq(await one(`select private.enc('')`), null, 'empty string -> null')
  eq(await one(`select private.dec_num(private.enc_num(8500000.50))`), '8500000.50', 'numeric round-trip')
  eq(await one(`select private.bidx('9876543210') = private.bidx('9876543210')`), true, 'blind index is deterministic')
  eq(await one(`select length(private.bidx('9876543210'))`), 64, 'blind index is 64 hex chars')
  eq(await one(`select public.normalize_phone('+91 98765-43210')`), '9876543210', 'normalize_phone strips +91 and symbols')
  eq(await one(`select public.normalize_phone('098765 43210')`), '9876543210', 'normalize_phone strips leading 0')
  eq(await one(`select public.phone_hint('9876543210')`), '98••••••10', 'phone_hint masks the middle')
  await denied(db.query(`select private.dec('\\x01ffff'::bytea)`), 'tampered ciphertext is rejected')
}

console.log('\n# Users')
const owner = await addUser(db, { username: 'owner', role: 'owner' })
const admin = await addUser(db, { username: 'admin1', role: 'admin' })
const mgr = await addUser(db, { username: 'manager1', role: 'manager', manager: owner })
const sales = await addUser(db, { username: 'sales1', role: 'sales', manager: mgr })
const sales2 = await addUser(db, { username: 'sales2', role: 'sales' })
const tc = await addUser(db, { username: 'tele1', role: 'telecaller', manager: mgr })
const analyst = await addUser(db, { username: 'analyst1', role: 'analyst' })
const gone = await addUser(db, { username: 'gone', role: 'sales', active: false })

console.log('\n# Permission engine')
eq(await as(db, owner, (u) => u.val(`select has_perm('settings')`)), true, 'owner (aal2) has settings')
eq(await as(db, owner, (u) => u.val(`select has_perm('settings')`), { aal: 'aal1' }), false, 'owner WITHOUT MFA has nothing')
eq(await as(db, admin, (u) => u.val(`select has_perm('leads')`), { aal: 'aal1' }), false, 'admin WITHOUT MFA has nothing')
eq(await as(db, sales, (u) => u.val(`select has_perm('leads')`), { aal: 'aal1' }), true, 'sales needs no MFA')
eq(await as(db, sales, (u) => u.val(`select has_perm('settings')`)), false, 'sales has no settings')
eq(await as(db, tc, (u) => u.val(`select has_perm('bookings')`)), false, 'telecaller has no bookings')
eq(await as(db, analyst, (u) => u.val(`select can_write('bookings')`)), false, 'analyst is read-only')
eq(await as(db, gone, (u) => u.val(`select has_perm('leads')`)), false, 'inactive user has nothing')
eq(await as(db, mgr, (u) => u.val(`select my_scope()`)), 'team', 'manager scope = team')
await db.query(`insert into user_overrides values ($1,'bookings',true), ($1,'leads',false)`, [tc])
eq(await as(db, tc, (u) => u.val(`select has_perm('bookings')`)), true, 'override grants a module')
eq(await as(db, tc, (u) => u.val(`select has_perm('leads')`)), false, 'override revokes a module')
await db.query(`delete from user_overrides`)
{
  const me = await as(db, sales, (u) => u.val(`select my_permissions()`))
  ok(me.granted.includes('leads') && !me.granted.includes('settings') && me.role === 'sales', 'my_permissions() lists effective grants')
}

console.log('\n# Lead visibility (RLS)')
const mkLead = (name, ownerId, creator) =>
  one(`insert into leads (name, phone_enc, phone_hint, phone_bidx, owner_id, created_by)
       values ($1, private.enc($2), phone_hint($2), private.bidx($2), $3, $4) returning id`,
    [name, String(9000000000 + Math.floor(Math.random() * 1e8)), ownerId, creator])
const lSales = await mkLead('Lead of sales1', sales, tc)
const lSales2 = await mkLead('Lead of sales2', sales2, sales2)
const names = (uid) => as(db, uid, async (u) => (await u.q(`select name from leads order by name`)).map((r) => r.name))
eq(await names(sales), ['Lead of sales1'], 'sales sees only own lead')
eq(await names(sales2), ['Lead of sales2'], 'other sales sees only theirs')
eq(await names(tc), ['Lead of sales1'], 'telecaller sees the lead they created')
eq(await names(mgr), ['Lead of sales1'], 'manager sees team leads only')
eq((await names(owner)).length, 2, 'owner sees all')
eq(await names(analyst), [], 'analyst (no leads module) sees none')
eq((await as(db, owner, (u) => u.q(`select 1 from leads`), { aal: 'aal1' })).length, 0, 'owner without MFA sees no leads')

