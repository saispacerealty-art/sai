console.log('\n# Login gate & lockout')
const gate = (u, ip) => asService(db, (s) => s.val(`select login_gate($1, $2)`, [u, ip]))
const rec = (u, ip, okk) => asService(db, (s) => s.q(`select login_record($1, $2, $3)`, [u, ip, okk]))
eq(await gate('sales1', '1.1.1.1'), 'ok', 'gate ok initially')
for (let i = 0; i < 5; i++) await rec('sales1', '1.1.1.1', false)
eq(await gate('sales1', '1.1.1.1'), 'locked', 'locked after 5 failures')
eq(await as(db, sales, (u) => u.val(`select has_perm('leads')`)), false, 'locked account loses permissions')
await rec('sales1', '1.1.1.1', true)
eq(await gate('sales1', '1.1.1.1'), 'ok', 'successful login clears the lock')
eq(await gate('gone', '1.1.1.1'), 'inactive', 'inactive account is refused')
eq(await gate('nobody', '1.1.1.1'), 'ok', 'unknown username is not revealed')
for (let i = 0; i < 30; i++) await rec('x' + i, '9.9.9.9', false)
eq(await gate('sales1', '9.9.9.9'), 'ip_blocked', 'IP blocked after 30 failures')
await denied(as(db, sales, (u) => u.q(`select login_gate('a','b')`)), 'browser cannot call login_gate')
await denied(as(db, sales, (u) => u.q(`select svc_revoke_sessions($1)`, [owner])), 'browser cannot call service helpers')

